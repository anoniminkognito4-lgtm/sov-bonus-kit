# ---------- множитель вехи (К срока с потолком) ----------
def mult(dev, cat, kfin=1.0, kpi=None):
    if dev <= -100:
        return 0.0
    x = {'РУПК': 1.0, 'МП': (kpi - 0.5) * 2 if kpi is not None else None, 'КУПК': kfin}[cat]
    cap = {'РУПК': 1.5, 'МП': x * 1.5 if x is not None else None, 'КУПК': 1.5 * kfin}[cat]
    return min((1 + dev / 100) * x, cap)


