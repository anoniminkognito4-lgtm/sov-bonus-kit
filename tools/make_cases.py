MS = [('Мотивационная веха 1', '2025-06-30'), ('Мотивационная веха 2', '2025-09-30'),
      ('Мотивационная веха 3', '2025-12-15'), ('Мотивационная веха 4', '2026-03-31'),
      ('Мотивационная веха 5', '2026-05-29'), ('Мотивационная веха 6', '2026-07-31')]
FINAL = {'name': 'Ключевая веха этапа', 'plan': '2026-09-30', 'fact': '2026-09-30'}
START = '2025-04-01'
_tab = [0]


def ms(facts=None):
    facts = facts or {}
    return [{'name': n, 'building': '', 'plan': p, 'fact': facts.get(n, p)} for n, p in MS]


def emp(fio, cat, **kw):
    _tab[0] += 1
    default_role = 'РП' if cat == 'КУПК (РП/ЗРП)' else 'другая'
    e = {'tab_no': 'T%04d' % _tab[0], 'fio': fio, 'category': cat, 'role': kw.pop('role', default_role),
         'position': kw.pop('position', 'Условная должность'), 'start': kw.pop('start', START),
         'npv_start': kw.pop('npv_start', None), 'npv_current': kw.pop('npv_current', None),
         'periods': kw.pop('periods', [{'from': START, 'to': '2026-09-30', 'bgb': 2400000, 'load': 1.0}])}
    if cat in ('КУПК', 'КУПК (РП/ЗРП)'):
        e['npv_start'] = e['npv_start'] or 5_000_000_000
        e['npv_current'] = e['npv_current'] or 5_000_000_000
        e['npv_checkpoints'] = kw.pop('npv_checkpoints', {'final': e['npv_current'], 'q1': e['npv_current'], 'q2': e['npv_current']})
    e.update(kw)
    return e


def case(cid, title, check, employees, **kw):
    c = {'id': cid, 'title': title, 'check': check, 'harness': kw.pop('harness', True),
         'project': 'Тестовый проект', 'stage': kw.pop('stage', 4),
         'continues_from_prev_stage': kw.pop('continues', False), 'new_stage_start': kw.pop('new_stage_start', None),
         'bs': kw.pop('bs', {'enabled': False, 'share_transferred': 1.0}),
         'milestones': kw.pop('milestones', ms()), 'final': kw.pop('final', dict(FINAL)),
         'key_rate': kw.pop('key_rate', 0.16), 'employees': employees}
    c.update(kw)
    with open(os.path.join(OUT, cid + '.json'), 'w', encoding='utf-8') as f:
        json.dump(c, f, ensure_ascii=False, indent=1)


